import {
  Activity,
  ArrowRight,
  Bell,
  Bot,
  Check,
  ChevronDown,
  ChevronRight,
  Code,
  ExternalLink,
  FolderKanban,
  Info,
  Languages,
  LayoutGrid,
  LogOut,
  Mail,
  Menu,
  MessageSquareText,
  Plug,
  Plus,
  RefreshCw,
  Search,
  Settings,
  ShieldCheck,
  Ticket,
  Clock,
  TriangleAlert,
  UserRound,
  Users,
  Workflow,
  X,
  type LucideIcon,
} from 'lucide-react';

const icons = {
  grid: LayoutGrid,
  ticket: Ticket,
  pulse: Activity,
  users: Users,
  user: UserRound,
  arrow: ArrowRight,
  plus: Plus,
  search: Search,
  clock: Clock,
  check: Check,
  warning: TriangleAlert,
  info: Info,
  logout: LogOut,
  chevron: ChevronRight,
  chevronDown: ChevronDown,
  shield: ShieldCheck,
  message: MessageSquareText,
  refresh: RefreshCw,
  external: ExternalLink,
  code: Code,
  plug: Plug,
  folder: FolderKanban,
  settings: Settings,
  bell: Bell,
  menu: Menu,
  close: X,
  language: Languages,
  mail: Mail,
  bot: Bot,
  flow: Workflow,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof icons;

export function Icon({ name, size = 20 }: { name: IconName; size?: number }) {
  const Glyph = icons[name];
  return <Glyph size={size} strokeWidth={1.75} aria-hidden="true" focusable="false" />;
}
